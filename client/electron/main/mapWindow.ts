import path from 'node:path'
import { BrowserWindow, shell } from 'electron'

/**
 * Battlemap windows, in one of two MODES:
 *
 *   'edit'  — the DM's own editor, on its own monitor. Full chrome, devtools
 *             allowed. The map needs a window because it needs the space: in a
 *             340px session rail there is no room to see a room.
 *   'table' — what the players look at. Chrome-free, and only ever sent a map
 *             that `forPlayers` has already stripped of hidden tokens.
 *
 * A sibling of playerWindow.ts rather than a third mode inside it, and the
 * reason is the id. That module guards every call with
 * `resolveInWorld(root, articleId + '.md')` — an article id is a world-relative
 * PATH, so resolving it is both meaningful and the security boundary. A map id
 * is an 8-char random string from `newMapId()`; there is no file to resolve, so
 * forcing one through that guard would mean the guard either lies or is skipped,
 * and skipping it inside a file whose comment says "every handler funnels
 * through the path guard" is how the next person reintroduces a traversal bug.
 * Here the id is validated for shape and the world root is the boundary.
 *
 * Electron-coupled, so untested — the state it displays is owned by
 * stateAuthority.ts and the rules are pure in src/lib/mapStore.ts.
 */

const devServerUrl = process.env.VITE_DEV_SERVER_URL

export type MapWindowMode = 'edit' | 'table'

/** `${mode}::${worldId}::${mapId}` -> the window showing it. */
const windows = new Map<string, BrowserWindow>()

const keyOf = (mode: MapWindowMode, worldId: string, mapId: string) =>
  `${mode}::${worldId}::${mapId}`

/**
 * Map ids are generated by `newMapId()` as 8 base-36 characters.
 *
 * Checked rather than resolved: the id rides in a URL hash and is looked up in
 * a JSON file, never joined onto a filesystem path, so the risk is a malformed
 * id reaching the router — not traversal. The world root is still guarded by
 * the caller.
 */
export function isMapId(value: unknown): value is string {
  return typeof value === 'string' && /^[a-z0-9]{1,32}$/i.test(value)
}

/** Open a window for this map, or focus the one already showing it. */
export function showMapWindow(
  worldId: string,
  mapId: string,
  mode: MapWindowMode = 'edit',
): void {
  const key = keyOf(mode, worldId, mapId)
  const existing = windows.get(key)
  if (existing && !existing.isDestroyed()) {
    if (existing.isMinimized()) existing.restore()
    existing.focus()
    return
  }

  const table = mode === 'table'
  const win = new BrowserWindow({
    width: table ? 1280 : 1400,
    height: table ? 800 : 900,
    show: false,
    autoHideMenuBar: true,
    // Matches the route's dark background: no white flash on open, which on a
    // projector is a flash the whole table sees.
    backgroundColor: '#0c0a09',
    title: table ? 'Battlemap' : 'Map editor',
    webPreferences: {
      // Identical to the DM window's. Notably NO `partition`: the world://
      // protocol is registered against the default session, so a partitioned
      // window would silently serve no images — which on a battlemap means a
      // blank grid where the map should be.
      preload: path.join(__dirname, '../preload/index.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
    },
  })

  win.once('ready-to-show', () => win.show())

  // Same two guards the DM window sets. They are per-webContents and are NOT
  // inherited.
  win.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:/i.test(url)) void shell.openExternal(url)
    return { action: 'deny' }
  })
  win.webContents.on('will-navigate', (e, url) => {
    const isApp = devServerUrl
      ? url.startsWith(devServerUrl)
      : url.startsWith('file:')
    if (isApp) return
    e.preventDefault()
    if (/^https?:/i.test(url)) void shell.openExternal(url)
  })

  // NO encodeURIComponent, unlike playerWindow.ts one line from here: an
  // article id is a path containing slashes and must be encoded, while a map id
  // is [a-z0-9] and encoding it is a no-op. Spelled out because the obvious
  // "fix" is to make this line match its neighbour, which would double-encode.
  const hash = `/${table ? 'mapview' : 'map'}/${worldId}/${mapId}`
  if (devServerUrl) {
    void win.loadURL(`${devServerUrl}/#${hash}`)
    // Deliberately no openDevTools for the table window: a detached devtools
    // pane on a projector is visible to the players.
  } else {
    void win.loadFile(path.join(__dirname, '../../dist/index.html'), { hash })
  }

  win.on('closed', () => {
    // Identity-checked: a fast close/reopen would otherwise have the old
    // window's event delete the new window's entry.
    if (windows.get(key) === win) windows.delete(key)
  })
  windows.set(key, win)
}

export function closeMapWindow(
  worldId: string,
  mapId: string,
  mode: MapWindowMode = 'edit',
): void {
  const win = windows.get(keyOf(mode, worldId, mapId))
  if (win && !win.isDestroyed()) win.close()
}

/** Close every map window. Returns how many were open. */
export function closeAllMapWindows(): number {
  // Iterate a copy: close() can fire 'closed' synchronously, which mutates the
  // map we would otherwise be walking.
  const open = [...windows.values()].filter((w) => !w.isDestroyed())
  for (const win of open) win.close()
  return open.length
}

/**
 * Close every map window belonging to a world other than this one.
 *
 * The DM switching worlds must not leave an editor open on a world the app no
 * longer considers open — it would keep writing to it, and its `world://` image
 * URLs point at a folder that is no longer current.
 */
export function closeMapWindowsExcept(worldId: string): Array<string> {
  const closed: Array<string> = []
  for (const [key, win] of [...windows.entries()]) {
    const [, owner] = key.split('::')
    if (owner === worldId || win.isDestroyed()) continue
    closed.push(owner)
    win.close()
  }
  return closed
}

/**
 * Whether this webContents is a players' map window.
 *
 * The gate the roll relay uses to keep raw rolls out of it: that window is a
 * display in front of the players, and gets the session only as the redacted
 * push `forPlayersSession` builds in the editor.
 */
export function isTableView(contents: { id: number }): boolean {
  for (const [key, win] of windows) {
    if (!key.startsWith('table::') || win.isDestroyed()) continue
    if (win.webContents.id === contents.id) return true
  }
  return false
}

/** Whether any window is showing this map to the table. */
export function isShowingToTable(worldId: string, mapId: string): boolean {
  const win = windows.get(keyOf('table', worldId, mapId))
  return !!win && !win.isDestroyed()
}

/**
 * Relay a map to the table window showing it.
 *
 * A no-op when no such window is open, so the editor never has to know whether
 * anyone is watching — the same contract `pushToPlayerWindow` offers.
 */
export function pushToMapWindow(payload: {
  worldId: string
  mapId: string
  map: unknown
  session?: unknown
}): void {
  const win = windows.get(keyOf('table', payload.worldId, payload.mapId))
  if (win && !win.isDestroyed()) win.webContents.send('map:live', payload)
}
